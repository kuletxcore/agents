import { readdirSync, readFileSync, writeFileSync } from "node:fs";

const dir = new URL("../migrations/", import.meta.url);
const sql = readdirSync(dir)
  .filter((name) => name.endsWith(".sql"))
  .sort()
  .map((name) => readFileSync(new URL(name, dir), "utf8"))
  .join("\n");
const out = `// Generated by scripts/sync-schema.mjs — do not edit.\nexport const SCHEMA_SQL = ${JSON.stringify(sql)};\n`;
writeFileSync(new URL("../worker/schema.ts", import.meta.url), out);
console.log("wrote worker/schema.ts");
