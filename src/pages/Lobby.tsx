import { useEffect, useState } from "react";
import { Link, useNavigate } from "react-router-dom";
import { api } from "../lib/api";
import { hello, money, pct, rel } from "../lib/format";
import { Button, Card, Meter, Ribbon, Sparkline, useCount } from "../components/ui";

type Dash = {
  range: string;
  rate: number;
  flatMonthly: number;
  kpis: {
    spent: { value: number; delta: number; series: number[] };
    saved: { value: number; hours: number; delta: number; series: number[] };
    roi: { value: number; delta: number; multiple: number; series: number[] };
  };
  sessions: { count: number; focus: number; delta: number; series: { day: string; sessions: number; focus: number }[] };
  subscriptions: { id: string; provider: string; plan: string; monthlyPrice: number; accent: string }[];
  windows: { id: string; provider: string; label: string; used: number; cap: number; unit: string; resets: string }[];
  dreams: { id: string; category: string; title: string; body: string; impact: string; status: string }[];
  skills: { id: string; name: string; category: string; invocations: number; est_minutes: number; saved: number }[];
  recommended: { id: string; name: string; state: string; category: string }[];
  memory: { notes: number; stale: number; conflicts: number; missing: number; signals: { action: string; path: string; at: string }[] };
  integrations: { id: string; name: string; connected: number }[];
  knowledge: { id: string; name: string; kind: string; countLabel: string; lastSync: string }[];
  schedules: { id: string; name: string; cadence: string; lastRun: string; nextRun: string; status: string }[];
  syncedAt: string;
};

const RANGES = [
  { id: "1d", label: "Today" },
  { id: "7d", label: "7 days" },
  { id: "28d", label: "28 days" },
];

export default function Lobby() {
  const [range, setRange] = useState("7d");
  const [data, setData] = useState<Dash | null>(null);
  const [error, setError] = useState<string | null>(null);
  const navigate = useNavigate();
  const hour = Number(
    new Intl.DateTimeFormat("en-US", { timeZone: "Asia/Manila", hour: "2-digit", hourCycle: "h23" }).format(new Date()),
  );

  useEffect(() => {
    setError(null);
    api<Dash>(`/api/dashboard?range=${range}`)
      .then(setData)
      .catch((e: Error) => setError(e.message));
  }, [range]);

  if (error) {
    return (
      <Card>
        <Ribbon tone="alert">Lobby offline</Ribbon>
        <p>{error}</p>
      </Card>
    );
  }
  if (!data) return <div className="linking">Linking lobby…</div>;

  const tokenBurn = data.kpis.spent.value;
  const multiple = data.flatMonthly > 0 ? (data.kpis.saved.value / data.flatMonthly).toFixed(1) : "—";

  return (
    <section>
      <header className="page-head">
        <div>
          <div className="kicker">OPERATOR // KULET · {data.range.toUpperCase()}</div>
          <h1>Lobby</h1>
          <p className="sub">
            {hello(hour)}, Kulet. {data.memory.notes} notes indexed · <Link to="/settings" style={{ textDecoration: "underline" }}>Model connection</Link> · synced {rel(data.syncedAt)}.
          </p>
        </div>
        <div className="seg" role="tablist" aria-label="Range">
          {RANGES.map((r) => (
            <button key={r.id} className={`chip ${range === r.id ? "on" : ""}`} onClick={() => setRange(r.id)}>
              <span>{r.label}</span>
            </button>
          ))}
        </div>
      </header>

      <div className="grid-3">
        <Kpi label="Spent on AI" value={data.kpis.spent.value} delta={data.kpis.spent.delta} series={data.kpis.spent.series} color="#d4924a" money />
        <Kpi label="Skills saved" value={data.kpis.saved.value} delta={data.kpis.saved.delta} series={data.kpis.saved.series} color="#128afa" money hint={`${data.kpis.saved.hours}h × $${data.rate}`} />
        <Kpi label="Net ROI" value={data.kpis.roi.value} delta={data.kpis.roi.delta} series={data.kpis.roi.series} color="#1f3b5e" money signed />
      </div>

      <div className="grid-2" style={{ marginTop: 14 }}>
        <Card>
          <div style={{ display: "flex", justifyContent: "space-between" }}>
            <Ribbon tone="cyan">{data.dreams.length} improvements filed overnight</Ribbon>
            <Button small tone="ghost" onClick={() => navigate("/dream")}>Open desk</Button>
          </div>
          <p className="muted">Pattern window 7 days · generated by Nightwatch</p>
          {data.dreams[0] ? (
            <div style={{ marginTop: 8 }}>
              <span className="tag">{data.dreams[0].category}</span>
              <h3 style={{ fontSize: 26, marginTop: 8 }}>{data.dreams[0].title}</h3>
              <p>{data.dreams[0].body}</p>
              <div className="muted">{data.dreams[0].impact}</div>
            </div>
          ) : (
            <p>Desk is clear. Nightwatch files the next set at 06:00 Manila.</p>
          )}
        </Card>
        <Card>
          <div style={{ display: "flex", justifyContent: "space-between" }}>
            <Ribbon>Skill value</Ribbon>
            <Button small tone="ghost" onClick={() => navigate("/skills")}>Show all</Button>
          </div>
          {data.skills.map((s) => (
            <div className="row" key={s.id}>
              <div>
                <strong>{s.name}</strong>
                <div className="muted">{s.category} · {s.invocations} runs · ~{s.est_minutes} min</div>
              </div>
              <b>{money(s.saved, 0)}</b>
            </div>
          ))}
        </Card>
      </div>

      <div className="grid-2" style={{ marginTop: 14 }}>
        <Card>
          <div style={{ display: "flex", justifyContent: "space-between", alignItems: "center" }}>
            <Ribbon>Subscriptions</Ribbon>
            <span className="muted mono">flat {money(data.flatMonthly, 0)}/mo · burn {money(tokenBurn)} · {multiple}× vs flat</span>
          </div>
          <div style={{ display: "grid", gridTemplateColumns: "repeat(auto-fit, minmax(140px, 1fr))", gap: 8, marginTop: 12 }}>
            {data.subscriptions.map((s) => (
              <button key={s.id} onClick={() => navigate("/business")} style={{ textAlign: "left", background: "transparent", border: 0, padding: 0 }}>
                <div style={{ borderLeft: `4px solid ${s.accent}`, padding: "6px 8px", background: "rgba(18,48,79,0.04)" }}>
                  <strong style={{ fontFamily: "var(--display)", fontStyle: "italic" }}>{s.provider}</strong>
                  <div className="muted">{s.plan}</div>
                  <div>{s.monthlyPrice ? money(s.monthlyPrice, 0) : "usage"}</div>
                </div>
              </button>
            ))}
          </div>
        </Card>
        <Card>
          <Ribbon tone="yellow">Plan windows</Ribbon>
          <div className="list" style={{ marginTop: 10 }}>
            {data.windows.map((w) => (
              <div key={w.id}>
                <div className="row" style={{ border: 0, paddingBottom: 4 }}>
                  <span><strong>{w.provider}</strong> <span className="muted">{w.label}</span></span>
                  <span className="mono">{w.used}/{w.cap} {w.unit}</span>
                </div>
                <Meter value={pct(w.used, w.cap)} tone={pct(w.used, w.cap) > 85 ? "alert" : ""} />
                <div className="muted" style={{ fontSize: 12, marginTop: 3 }}>{w.resets}</div>
              </div>
            ))}
          </div>
        </Card>
      </div>

      <div className="grid-2" style={{ marginTop: 14 }}>
        <Card>
          <div style={{ display: "flex", justifyContent: "space-between" }}>
            <Ribbon>Knowledge</Ribbon>
            <Button small onClick={() => navigate("/memory")}>Open map</Button>
          </div>
          <p className="muted">{data.memory.notes} notes · {data.memory.stale} stale · {data.memory.conflicts} conflicts · {data.memory.missing} missing</p>
          {data.memory.signals.map((s) => (
            <div className="row" key={s.path + s.at}>
              <span><span className="tag navy">{s.action}</span> {s.path}</span>
              <span className="muted">{rel(s.at)}</span>
            </div>
          ))}
          <div style={{ marginTop: 8 }}>
            {data.knowledge.map((k) => (
              <div key={k.id} className="row">
                <div><strong>{k.name}</strong><div className="muted">{k.kind} · {k.countLabel}</div></div>
                <span className="muted">{rel(k.lastSync)}</span>
              </div>
            ))}
          </div>
        </Card>
        <Card>
          <div style={{ display: "flex", justifyContent: "space-between" }}>
            <Ribbon>What’s linked</Ribbon>
            <Button small tone="ghost" onClick={() => navigate("/integrations")}>All links</Button>
          </div>
          <div style={{ display: "flex", flexWrap: "wrap", gap: 6, marginTop: 10 }}>
            {data.integrations.map((i) => (
              <span key={i.id} className={`tag ${i.connected ? "ok" : ""}`}>{i.name}</span>
            ))}
          </div>
          <h3 style={{ marginTop: 16 }}>Sessions</h3>
          <p className="muted">{data.sessions.count} sessions · {data.sessions.focus} focus hours · {data.sessions.delta >= 0 ? "+" : ""}{data.sessions.delta}% vs prior</p>
          <div style={{ display: "flex", alignItems: "flex-end", gap: 4, height: 72 }}>
            {data.sessions.series.map((s) => (
              <div key={s.day} title={`${s.day}: ${s.sessions}`} style={{ flex: 1, height: `${8 + s.sessions * 7}px`, background: "linear-gradient(#4ac8ff, #128afa)", transform: "skewX(-8deg)" }} />
            ))}
          </div>
        </Card>
      </div>

      <div style={{ marginTop: 14 }}><Card>
        <div style={{ display: "flex", justifyContent: "space-between" }}>
          <Ribbon tone="yellow">Patrol</Ribbon>
          <Button small tone="ghost" onClick={() => navigate("/automations")}>Schedules</Button>
        </div>
        <table className="table">
          <thead><tr><th>NAME</th><th>CADENCE</th><th>LAST</th><th>NEXT</th><th>STATUS</th></tr></thead>
          <tbody>
            {data.schedules.map((s) => (
              <tr key={s.id}>
                <td>{s.name}</td>
                <td className="mono">{s.cadence}</td>
                <td>{rel(s.lastRun)}</td>
                <td>{rel(s.nextRun)}</td>
                <td><span className={`tag ${s.status === "ok" ? "ok" : "bad"}`}>{s.status}</span></td>
              </tr>
            ))}
          </tbody>
        </table>
        <div style={{ marginTop: 8 }}>
          <Ribbon>Recommended</Ribbon>
          <div style={{ display: "flex", gap: 8, flexWrap: "wrap", marginTop: 8 }}>
            {data.recommended.map((s) => (
              <button key={s.id} className="chip" onClick={() => navigate("/skills")}><span>{s.name} · {s.state}</span></button>
            ))}
          </div>
        </div>
      </Card></div>
    </section>
  );
}

function Kpi({
  label, value, delta, series, color, money: asMoney, signed, hint,
}: {
  label: string;
  value: number;
  delta: number;
  series: number[];
  color: string;
  money?: boolean;
  signed?: boolean;
  hint?: string;
}) {
  const shown = useCount(value);
  const text = asMoney ? `${signed && shown > 0 ? "+" : ""}${money(shown)}` : shown.toFixed(0);
  return (
    <Card>
      <div style={{ display: "flex", justifyContent: "space-between", gap: 8 }}>
        <Ribbon tone={label.startsWith("Net") ? "yellow" : label.startsWith("Spent") ? "" : "cyan"}>{label}</Ribbon>
        <Sparkline data={series} color={color} />
      </div>
      <div className="stat" style={{ marginTop: 10 }}>{text}</div>
      <div className={delta >= 0 ? "delta" : "delta down"}>{delta >= 0 ? "+" : ""}{delta}% vs prior {hint ? `· ${hint}` : ""}</div>
    </Card>
  );
}
